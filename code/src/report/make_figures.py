#!/usr/bin/env python3
"""Write the source of the summary results figure (results.tex) from the
processed results, so every plotted number comes from a results file.

    python3 src/report/make_figures.py      (run from code/)

Reads ../supplementary/experimental_results/{wsl,vm}/ and writes
../latex_report/figures/source/results.tex. Compile it with pdflatex and render
the PDF to ../latex_report/figures/results.png (see the reproducibility guide).
The architecture and workflow figures are hand-drawn sources in the same folder.

Panels: (a) macro-F1 by evidence source, WSL and VM; (b) H2: high-confidence
error forced vs abstaining; (c) traced vs kernel I/O-blocked time in the delay
sweep; (d) tracing overhead per workload against the 10% budget.
"""
import argparse
import json
import os

SOURCES = [("syscall", "Syscall"), ("block", "Block"), ("scheduler", "Sched"),
           ("scheduler_noiowait", "Sched,\\\\no iowait"), ("fused_noiowait", "Fused,\\\\no iowait"),
           ("fused", "Fused")]
OVERHEAD = [("sleep", "sleep"), ("sync_write", "sync\\_write"), ("cpu", "cpu"),
            ("direct_read", "direct\\_read"), ("cold_read", "cold\\_read"), ("mixed", "mixed"),
            ("warm_read", "warm\\_read"), ("buffered_write", "buffered\\_write")]


def load(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def bars_f1(res, model):
    """pgfplots coordinates with asymmetric CI error bars for one model family."""
    out = []
    for i, (key, _) in enumerate(SOURCES):
        m = res["main"][f"{model}/{key}"]
        lo, hi = m["macro_f1_ci"]
        f = m["macro_f1"]
        out.append(f"({i},{f:.4f}) +- (0,0) += (0,{hi - f:.4f}) -= (0,{f - lo:.4f})")
    return " ".join(out)


def delay_points(delay):
    pts = []
    for key, per in delay.items():
        if key.startswith("sleep"):
            continue        # sleep: no I/O wait is traced (correct), cannot be shown on log axes
        for d, v in per.items():
            if not isinstance(v, dict):     # per-workload summaries such as the slope
                continue
            if v["trace_io_blocked_us"] > 0 and v["kernel_blocked_us"] > 0:
                pts.append((v["kernel_blocked_us"] / 1e3, v["trace_io_blocked_us"] / 1e3, v["abs_err_us"]))
    return pts


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--results", default="../supplementary/experimental_results")
    ap.add_argument("--out", default="../latex_report/figures/source/results.tex")
    a = ap.parse_args()
    w = load(os.path.join(a.results, "wsl", "results-ref", "results.json"))
    v = load(os.path.join(a.results, "vm", "results-ref", "results.json"))
    dw = load(os.path.join(a.results, "wsl", "delay.json"))
    dv = load(os.path.join(a.results, "vm", "delay.json"))
    ov = load(os.path.join(a.results, "wsl", "overhead-v2.json"))
    budget = 100 * ov["budget"]["throughput_loss"]

    # (b) H2
    h2 = []
    for env, res in (("WSL", w), ("VM", v)):
        for model, name in (("rules/fused", "rules"), ("tree/fused", "tree")):
            h = res["H2"][model]
            h2.append((f"{env} {name}\\\\(abstains {100 * h['abstention']:.0f}\\%)",
                       100 * h["hc_error_forced"], 100 * h["hc_error_abstain"], 100 * h["abstention"]))
    h2_labels = ",".join("{" + x[0] + "}" for x in h2)
    h2_forced = " ".join(f"({i},{x[1]:.2f})" for i, x in enumerate(h2))
    h2_abst = " ".join(f"({i},{x[2]:.2f})" for i, x in enumerate(h2))

    # (c) delay sweep
    pw, pv = delay_points(dw), delay_points(dv)
    maxerr = {"WSL": max(p[2] for p in pw), "VM": max(p[2] for p in pv)}
    cw = " ".join(f"({x:.4f},{y:.4f})" for x, y, _ in pw)
    cv = " ".join(f"({x:.4f},{y:.4f})" for x, y, _ in pv)

    # (d) overhead, WSL, tracing on
    loss1, loss4 = [], []
    for i, (key, _) in enumerate(OVERHEAD):
        for thr, lst in ((1, loss1), (4, loss4)):
            g = ov["groups"].get(f"{key}/{thr}/on")
            lst.append(f"({100 * g['throughput_loss']['median']:.1f},{i})" if g else "")
    ov_labels = ",".join("{" + n + "}" for _, n in OVERHEAD)

    f1_labels = ",".join("{" + n + "}" for _, n in SOURCES)
    tex = rf"""% Generated by code/src/report/make_figures.py from supplementary/experimental_results.
% Do not edit by hand; rerun the script instead.
\documentclass[border=6pt]{{standalone}}
\usepackage[T1]{{fontenc}}
\usepackage{{helvet}}
\renewcommand{{\familydefault}}{{\sfdefault}}
\usepackage{{pgfplots}}
\pgfplotsset{{compat=1.17}}
\usepgfplotslibrary{{groupplots}}
\definecolor{{wsl}}{{HTML}}{{1F4E8C}}
\definecolor{{wsl2}}{{HTML}}{{7FA7D9}}
\definecolor{{vm}}{{HTML}}{{B35C00}}
\definecolor{{vm2}}{{HTML}}{{F2B66D}}
\definecolor{{bad}}{{HTML}}{{C0392B}}
\definecolor{{good}}{{HTML}}{{2E9D57}}
\begin{{document}}
\begin{{tikzpicture}}[font=\footnotesize]
\begin{{groupplot}}[group style={{group size=2 by 2, horizontal sep=26mm, vertical sep=30mm}},
  width=95mm, height=62mm, title style={{font=\bfseries\small, align=center}},
  tick label style={{font=\scriptsize}}, label style={{font=\footnotesize}},
  legend style={{font=\scriptsize, draw=none, fill=none, legend columns=4,
                at={{(0.5,1.02)}}, anchor=south}}, ymajorgrids, grid style={{gray!20}}]

% (a) macro-F1 by evidence source
\nextgroupplot[title={{(a) Macro-F1 by evidence source (test runs, 95\% CI)}},
  title style={{yshift=7mm}},
  ybar, bar width=4.2pt, ymin=0, ymax=1.05, ylabel={{Macro-F1}},
  xtick={{0,...,5}}, xticklabels={{{f1_labels}}}, xticklabel style={{align=center}},
  enlarge x limits=0.09, error bars/error bar style={{line width=0.5pt, black}}]
\addplot+[fill=wsl, draw=wsl, error bars/.cd, y dir=both, y explicit] coordinates {{{bars_f1(w, "rules")}}};
\addplot+[fill=wsl2, draw=wsl2, error bars/.cd, y dir=both, y explicit] coordinates {{{bars_f1(w, "tree")}}};
\addplot+[fill=vm, draw=vm, error bars/.cd, y dir=both, y explicit] coordinates {{{bars_f1(v, "rules")}}};
\addplot+[fill=vm2, draw=vm2, error bars/.cd, y dir=both, y explicit] coordinates {{{bars_f1(v, "tree")}}};
\legend{{WSL rules, WSL tree, VM rules, VM tree}}

% (b) H2: abstention
\nextgroupplot[title={{(b) H2: wrong confident labels, forced vs abstaining}},
  title style={{yshift=7mm}},
  ybar, bar width=9pt, ymin=0, ymax=27, ylabel={{High-confidence error (\%)}},
  xtick={{0,...,3}}, xticklabels={{{h2_labels}}}, xticklabel style={{align=center}},
  enlarge x limits=0.18, nodes near coords, nodes near coords style={{font=\scriptsize, text=black}},
  every node near coord/.append style={{/pgf/number format/.cd, fixed, fixed zerofill, precision=1}}]
\addplot+[fill=bad, draw=bad] coordinates {{{h2_forced}}};
\addplot+[fill=good, draw=good] coordinates {{{h2_abst}}};
\legend{{forced to choose, may answer INDETERMINATE}}

% (c) delay sweep
\nextgroupplot[title={{(c) Stall time: traced vs kernel, injected delay 0/5/20 ms}},
  xmode=log, ymode=log, xmin=0.3, xmax=700, ymin=0.3, ymax=700,
  xlabel={{Kernel blocked time per op (ms)}}, ylabel={{Traced I/O-blocked time per op (ms)}},
  xmajorgrids, legend style={{at={{(0.03,0.97)}}, anchor=north west, legend columns=1,
  fill=white, draw=gray!40}}]
\addplot[only marks, mark=o, mark size=2.2pt, wsl, thick] coordinates {{{cw}}};
\addplot[only marks, mark=triangle, mark size=2.6pt, vm, thick] coordinates {{{cv}}};
\addplot[gray, dashed, domain=0.3:700, samples=2] {{x}};
\legend{{WSL (max error {maxerr["WSL"]:.0f}\,\textmu s), VM (max error {maxerr["VM"]:.0f}\,\textmu s), traced = kernel}}

% (d) overhead
\nextgroupplot[title={{(d) Tracing overhead (WSL): throughput loss}},
  xbar, bar width=4.5pt, xmin=-10, xmax=100, xlabel={{Throughput loss with tracing on (\%)}},
  ytick={{0,...,{len(OVERHEAD) - 1}}}, yticklabels={{{ov_labels}}}, y dir=reverse,
  enlarge y limits=0.08, ymajorgrids=false, xmajorgrids, clip=false,
  legend style={{at={{(0.97,0.97)}}, anchor=north east, legend columns=1, fill=white, draw=gray!40}}]
\addplot+[fill=wsl, draw=wsl] coordinates {{{" ".join(c for c in loss1 if c)}}};
\addplot+[fill=wsl2, draw=wsl2] coordinates {{{" ".join(c for c in loss4 if c)}}};
\draw[bad, thick, dashed] (axis cs:{budget:.0f},-0.6) -- (axis cs:{budget:.0f},{len(OVERHEAD) - 0.4});
\node[bad, font=\scriptsize, anchor=south, fill=white, inner sep=1pt] at (axis cs:{budget:.0f},-0.6) {{{budget:.0f}\% budget}};
\legend{{1 thread, 4 threads}}
\end{{groupplot}}
\end{{tikzpicture}}
\end{{document}}
"""
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    with open(a.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(tex)
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()
